import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// Workers static assets reject anything larger than this.
const MAX_ASSET_BYTES = 25 * 1024 * 1024;

function filesIn(dir, pattern) {
  const full = path.join(root, dir);
  let entries = [];
  try {
    entries = readdirSync(full, { withFileTypes: true });
  } catch (error) {
    if (error && error.code === "ENOENT") return { servable: [], oversized: [] };
    throw error;
  }

  const servable = [];
  const oversized = [];
  entries.forEach(function (entry) {
    if (!entry.isFile() || entry.name.startsWith(".")) return;
    if (!pattern.test(entry.name)) return;
    const rel = dir + "/" + entry.name;
    const size = statSync(path.join(full, entry.name)).size;
    if (size > MAX_ASSET_BYTES) oversized.push(rel);
    else servable.push(entry.name);
  });
  servable.sort(function (a, b) { return a.localeCompare(b); });
  oversized.sort(function (a, b) { return a.localeCompare(b); });
  return { servable: servable, oversized: oversized };
}

const music = filesIn("music", /\.(mp3|mid|midi)$/i);
const games = filesIn("games", /\.zip$/i);
const oversized = music.oversized.concat(games.oversized);

const catalog = [
  "// Generated by scripts/catalog.mjs when Wrangler builds the Worker.",
  "export const music = " + JSON.stringify(music.servable, null, 2) + ";",
  "export const games = " + JSON.stringify(games.servable, null, 2) + ";",
  ""
].join("\n");

writeFileSync(path.join(root, "worker", "catalog.js"), catalog);

const ignore = [
  ".git",
  ".wrangler",
  ".DS_Store",
  "worker",
  "scripts",
  "wrangler.jsonc",
  "node_modules"
].concat(oversized).join("\n") + "\n";

writeFileSync(path.join(root, ".assetsignore"), ignore);
